class TraceabilityDataProvider implements vscode.TreeDataProvider<{ key: string; label: string; status: string }> {
  private _onDidChangeTreeData = new vscode.EventEmitter<void>();
  readonly onDidChangeTreeData = this._onDidChangeTreeData.event;

  getTreeItem(element: { key: string; label: string; status: string }): vscode.TreeItem {
    const item = new vscode.TreeItem(element.label);
    item.description = element.status;
    item.tooltip = `${element.label}: ${element.status}`;
    item.contextValue = element.key;
    return item;
  }

  getChildren(): { key: string; label: string; status: string }[] {
    return [
      { key: 'signup', label: 'Unified Signup/Signin', status: '✅ Approved' },
      { key: 'roles', label: 'Role-based Access', status: '✅ Approved' },
      { key: 'audit', label: 'Audit Logs', status: '🔍 In Review' },
      { key: 'compliance', label: 'Compliance Enforcement', status: '✅ Approved' },
      { key: 'uiux', label: 'UI/UX Design', status: '✅ Approved' },
      { key: 'arch', label: 'Architectural Guidance', status: '⏳ Pending' },
      { key: 'cli', label: 'CLI Extension', status: '⏳ Pending' },
    ];
  }
}

